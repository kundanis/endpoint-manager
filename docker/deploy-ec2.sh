#!/usr/bin/env bash
# Endpoint IQ - one-command deployment on a fresh Linux host (AWS EC2: Amazon Linux 2023 or
# Ubuntu 22.04/24.04, x86_64).
#
#   git clone https://github.com/kundanis/endpoint-one.git
#   cd endpoint-one/docker
#   ./deploy-ec2.sh
#
# What it does (safe to re-run - it never overwrites an existing .env or database):
#   1. Installs Docker Engine + the compose plugin if missing.
#   2. Creates docker/.env with strong random secrets if it doesn't exist yet, and prints the
#      first administrator's login once.
#   3. Builds (or reuses a loaded) endpoint-one-server image and starts server + SQL Server.
#   4. Waits for the server to report healthy and prints the console URL.
#
# Options:
#   --no-build   use an already-loaded image (docker load -i endpoint-one-server.tar.gz)
#                instead of building from source - recommended on small instances.
set -euo pipefail

cd "$(dirname "$0")"
BUILD=1
[ "${1:-}" = "--no-build" ] && BUILD=0

log() { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
die() { printf '\nERROR: %s\n' "$*" >&2; exit 1; }

SUDO=""
[ "$(id -u)" -ne 0 ] && SUDO="sudo"

# --- 0. Sanity -------------------------------------------------------------------------------
arch="$(uname -m)"
[ "$arch" = "x86_64" ] || die "SQL Server needs an x86_64 host (got $arch). Use t3/m6i/m7i, not Graviton (t4g/m7g)."

mem_kb="$(awk '/MemTotal/ {print $2}' /proc/meminfo)"
if [ "$mem_kb" -lt 3800000 ]; then
  echo "WARNING: less than 4 GB RAM. SQL Server needs ~2 GB and building the image needs more;"
  echo "         use t3.medium or larger, or build elsewhere and run with --no-build."
fi

# --- 1. Docker -------------------------------------------------------------------------------
if ! command -v docker >/dev/null 2>&1; then
  log "Installing Docker"
  # Subshell: sourcing /etc/os-release would overwrite this script's variables.
  os_id="$( (. /etc/os-release 2>/dev/null && echo "${ID:-}") || true)"
  case "$os_id" in
    amzn)
      $SUDO dnf install -y docker
      # Compose v2 plugin (not packaged on Amazon Linux 2023).
      $SUDO mkdir -p /usr/local/lib/docker/cli-plugins
      $SUDO curl -fsSL "https://github.com/docker/compose/releases/latest/download/docker-compose-linux-x86_64" \
        -o /usr/local/lib/docker/cli-plugins/docker-compose
      $SUDO chmod +x /usr/local/lib/docker/cli-plugins/docker-compose
      # Buildx is needed by recent compose for `build:`.
      $SUDO curl -fsSL "$(curl -fsSL https://api.github.com/repos/docker/buildx/releases/latest \
        | grep -o 'https://[^"]*linux-amd64' | head -1)" -o /usr/local/lib/docker/cli-plugins/docker-buildx
      $SUDO chmod +x /usr/local/lib/docker/cli-plugins/docker-buildx
      ;;
    ubuntu|debian)
      curl -fsSL https://get.docker.com | $SUDO sh
      ;;
    *)
      die "Unsupported OS '${os_id:-unknown}'. Install Docker + compose plugin manually, then re-run."
      ;;
  esac
  $SUDO systemctl enable --now docker
  [ -n "$SUDO" ] && $SUDO usermod -aG docker "$USER" || true
fi
docker compose version >/dev/null 2>&1 || $SUDO docker compose version >/dev/null 2>&1 \
  || die "docker compose plugin not found."

# Use sudo for docker until the user's new group membership applies (next login).
DOCKER="docker"
docker info >/dev/null 2>&1 || DOCKER="$SUDO docker"

# --- 2. Secrets (.env) ----------------------------------------------------------------------
if [ ! -f .env ]; then
  log "Creating .env with generated secrets"
  rand() { openssl rand -base64 "$1" | tr -d '\n'; }
  # SQL Server complexity: upper + lower + digit + symbol.
  sa_password="Sa1!$(openssl rand -hex 12)"
  admin_password="Adm1!$(openssl rand -hex 8)"
  admin_email="${ADMIN_EMAIL:-admin@endpointone.local}"
  umask 077
  cat > .env <<EOF
# Generated by deploy-ec2.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep this file private.
SA_PASSWORD=${sa_password}
# Password of the restricted SQL login (endpoint_app) the server uses; sa is only used for migrations.
APP_DB_PASSWORD=App1!$(openssl rand -hex 16)
JWT_SECRET=$(rand 48)
# BACK THIS UP: losing it makes encrypted fields permanently unrecoverable.
FIELD_ENCRYPTION_KEY=$(rand 32)
ADMIN_EMAIL=${admin_email}
ADMIN_PASSWORD=${admin_password}
DB_NAME=EndpointManagerDb
LICENSE_ENFORCEMENT_ENABLED=false
EOF
  echo "First administrator login (shown once - also stored in docker/.env):"
  echo "  email:    ${admin_email}"
  echo "  password: ${admin_password}"
else
  log "Using existing .env"
  # .env files from before the restricted SQL login existed: add its password once.
  if ! grep -qE '^APP_DB_PASSWORD=.' .env; then
    {
      echo "# Password of the restricted SQL login (endpoint_app) the server uses; sa is only used for migrations."
      echo "APP_DB_PASSWORD=App1!$(openssl rand -hex 16)"
    } >> .env
  fi
fi

# --- 3. Agent installers ---------------------------------------------------------------------
if [ ! -f agent-installer/EndpointProAgentSetup.exe ]; then
  echo
  echo "NOTE: docker/agent-installer/ has no EndpointProAgentSetup.exe yet. The console works,"
  echo "      but 'Download agent installer' will report it as missing until you copy in"
  echo "      EndpointProAgentSetup.exe, EndpointProAgentInstaller.zip and agent-manifest.json"
  echo "      (built on Windows with: npm run package -w @em/agent). No restart needed."
fi

# --- 4. Start ---------------------------------------------------------------------------------
if [ "$BUILD" -eq 1 ]; then
  log "Building image and starting (first build takes several minutes)"
  $DOCKER compose up -d --build
else
  $DOCKER image inspect endpoint-one-server:latest >/dev/null 2>&1 \
    || die "Image endpoint-one-server:latest not loaded. Run: docker load -i endpoint-one-server.tar.gz"
  log "Starting with the loaded image"
  $DOCKER compose up -d --no-build
fi

log "Waiting for the server to become healthy (first start creates and migrates the database)"
for _ in $(seq 1 60); do
  status="$($DOCKER inspect -f '{{.State.Health.Status}}' "$($DOCKER compose ps -q server)" 2>/dev/null || echo starting)"
  [ "$status" = "healthy" ] && break
  [ "$status" = "unhealthy" ] && { $DOCKER compose logs --tail 80 server; die "Server is unhealthy (logs above)."; }
  sleep 5
done
[ "${status:-}" = "healthy" ] || { $DOCKER compose logs --tail 80 server; die "Server did not become healthy in time."; }

# EC2 public IP via IMDSv2 (token required by default); falls back to the first local address.
imds_token="$(curl -fs -m 2 -X PUT http://169.254.169.254/latest/api/token \
  -H 'X-aws-ec2-metadata-token-ttl-seconds: 60' 2>/dev/null || true)"
ip="$(curl -fs -m 2 -H "X-aws-ec2-metadata-token: ${imds_token}" \
  http://169.254.169.254/latest/meta-data/public-ipv4 2>/dev/null || true)"
# Best effort only - never fail the install over a cosmetic lookup (minimal images lack hostname).
[ -n "$ip" ] || ip="$( (hostname -I 2>/dev/null || true) | awk '{print $1}')"
[ -n "$ip" ] || ip="<server-ip>"
log "Endpoint IQ is running"
echo "  Console:  http://${ip}:4000"
echo "  Next:     sign in, then Endpoint Hub -> Enrollment tokens -> Server connection details:"
echo "            set the address agents use (e.g. http://${ip}:4000) before downloading installers."
echo "  Logs:     docker compose logs -f server"
